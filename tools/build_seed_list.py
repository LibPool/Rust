def main() -> int:
    out = Path(__file__).resolve().parent.parent / "tools" / "seeds"
    out.mkdir(parents=True, exist_ok=True)
    data = [{"name": name, "tags": tags} for name, tags in SEEDS]
    (out / "rust.json").write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {len(data)} seeds to {out / 'rust.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
